def emit(text):
    data = text.encode("ascii", "replace")
    out = getattr(sys.stdout, "buffer", None)
    if out is not None:
        out.write(data)
        out.flush()
    else:
        sys.stdout.write(data.decode("ascii"))
        sys.stdout.flush()


